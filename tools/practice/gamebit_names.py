"""Generate the practice payload's game-bit name table from main/gamebit_ids.h.

Every named GameBitId becomes a log label indexed directly by bit id. Ids with
more than one name keep all of them, joined with '|', in header order.
Regenerate after renaming bits, then format the result:

    python tools/practice/gamebit_names.py
    clang-format -i include/practice/gamebit_names.h
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "include/main/gamebit_ids.h"
OUTPUT = ROOT / "include/practice/gamebit_names.h"
ENTRY = re.compile(r"^\s*GAMEBIT_(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", re.MULTILINE)
NO_NAME = 0xFFFF


def names(text=None):
    table = {}
    for name, value in ENTRY.findall(text if text is not None else SOURCE.read_text()):
        table.setdefault(int(value, 16), []).append(name)
    return {bit: "|".join(labels) for bit, labels in table.items()}


def render(table):
    count = max(table) + 1
    offsets, blob = [], []
    size = 0
    for bit in range(count):
        if bit in table:
            offsets.append(size)
            blob.append(table[bit])
            size += len(table[bit]) + 1
        else:
            offsets.append(NO_NAME)
    if size >= NO_NAME:
        raise ValueError("Game-bit name text exceeds 16-bit offsets")
    lines = [
        "/* Generated by tools/practice/gamebit_names.py from main/gamebit_ids.h. */",
        "#ifndef PRACTICE_GAMEBIT_NAMES_H",
        "#define PRACTICE_GAMEBIT_NAMES_H",
        "#ifdef SFA_PRACTICE",
        f"#define PRACTICE_GAMEBIT_NAME_COUNT {count}",
        f"#define PRACTICE_GAMEBIT_NO_NAME     0x{NO_NAME:X}",
        "static const u16 practiceGameBitNameOffsets[PRACTICE_GAMEBIT_NAME_COUNT] = {",
    ]
    for i in range(0, count, 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in offsets[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const char practiceGameBitNameText[] =")
    lines.extend(f'    "{name}\\0"' for name in blob)
    lines[-1] += ";"
    lines += ["#endif", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    table = names()
    args.output.write_text(render(table))
    print(f"Wrote {len(table)} game-bit names to {args.output}")


if __name__ == "__main__":
    main()
