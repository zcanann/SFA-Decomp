CODE_SECTIONS = {"init", "text"}
ZERO_SECTIONS = {"bss", "sbss", "sbss2"}
SECTION_INDEX = {
    "init": 0,
    "text": 1,
    "extab": 7,
    "extabindex": 8,
    "ctors": 9,
    "dtors": 10,
    "rodata": 11,
    "data": 12,
    "sdata": 13,
    "sdata2": 14,
}
TOP16_MASK_OPCODES = {
    7,
    8,
    10,
    11,
    12,
    13,
    14,
    15,
    24,
    25,
    26,
    27,
    28,
    29,
    *range(32, 56),
}
TOP16_LOW2_MASK_OPCODES = {56, 57, 60, 61}
SPLIT_RANGE_RE = re.compile(
    r"^\s*(\.?\S+)\s+start:0x([0-9A-Fa-f]+)\s+end:0x([0-9A-Fa-f]+)"
)


@dataclass(frozen=True)
class SplitRange:
    unit: str
    section: str
    start: int
    end: int


@dataclass(frozen=True)
class PortedRange:
    source: SplitRange
    target_start: int
    target_end: int
    source_functions: tuple[FunctionSymbol, ...]
    target_functions: tuple[FunctionSymbol, ...]


@dataclass(frozen=True)
class SymbolSpan:
    name: str
    section: str
    start: int
    end: int

    @property
    def size(self) -> int:
        return self.end - self.start


def mask_instruction(word: int) -> int:
    opcode = word >> 26
    if opcode == 18:
        return word & 0xFC000003
    if opcode == 16:
        return word & 0xFFFF0003
    if opcode in TOP16_MASK_OPCODES:
        return word & 0xFFFF0000
    if opcode in TOP16_LOW2_MASK_OPCODES:
        return word & 0xFFFF0003
    return word


def read_dol_range(dol: DolFile, start: int, size: int) -> bytes:
    for section in dol.sections:
        if section.address <= start and start + size <= section.address + section.size:
            offset = section.offset + start - section.address
            return dol.data[offset : offset + size]
    raise ValueError(f"Range 0x{start:08X}-0x{start + size:08X} is outside {dol.path}")


def verified_dol(path: Path, config_path: Path) -> DolFile:
    """Require the configured retail identity before projecting any boundaries."""
    match = re.search(
        r"^hash:[ \t]*(?P<quote>['\"]?)(?P<hash>[0-9a-fA-F]{40})(?P=quote)[ \t]*(?:#.*)?$",
        config_path.read_text(encoding="utf-8"), re.MULTILINE,
    )
    if match is None:
        raise ValueError(f"Missing or unsupported retail SHA-1 in {config_path}")
    dol = DolFile(path)
    actual = hashlib.sha1(dol.data).hexdigest()
    expected = match.group("hash").lower()
    if actual != expected:
        raise ValueError(f"Retail hash mismatch for {path}: expected {expected}, got {actual}")
    return dol


def function_signature(dol: DolFile, function: FunctionSymbol) -> bytes:
    raw = read_dol_range(dol, function.address, function.size)
    if len(raw) % 4:
        raise ValueError(
            f"Function {function.name} has non-word size 0x{function.size:X}"
        )
    digest = hashlib.sha1()
    for (word,) in struct.iter_unpack(">I", raw):
        digest.update(struct.pack(">I", mask_instruction(word)))
    return digest.digest()


def load_splits(path: Path) -> tuple[list[str], list[SplitRange]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    header_end = len(lines)
    ranges: list[SplitRange] = []
    unit: str | None = None
    for index, line in enumerate(lines):
        if line and not line[0].isspace() and ":" in line:
            unit_name, _, _ = line.partition(":")
            if unit_name == "Sections":
                continue
            if header_end == len(lines):
                header_end = index
            unit = unit_name
            continue
        if unit is None:
            continue
        match = SPLIT_RANGE_RE.match(line)
        if match is None:
            continue
        section = match.group(1).removeprefix(".")
        ranges.append(
            SplitRange(
                unit=unit.replace("\\", "/"),
                section=section,
                start=int(match.group(2), 16),
                end=int(match.group(3), 16),
            )
        )
    while header_end > 0 and not lines[header_end - 1].strip():
        header_end -= 1
    return lines[:header_end], ranges


def functions_in_range(
    functions_by_section: dict[str, list[FunctionSymbol]], split: SplitRange
) -> tuple[FunctionSymbol, ...]:
    return tuple(
        function
        for function in functions_by_section.get(split.section, [])
        if split.start <= function.address
        and function.address + function.size <= split.end
    )


def unique_function_matches(
    source_dol: DolFile,
    source_functions: list[FunctionSymbol],
    target_dol: DolFile,
    target_functions: list[FunctionSymbol],
) -> dict[int, FunctionSymbol]:
    source_by_signature: dict[tuple[str, bytes], list[FunctionSymbol]] = defaultdict(
        list
    )
    target_by_signature: dict[tuple[str, bytes], list[FunctionSymbol]] = defaultdict(
        list
    )
    source_by_name: dict[str, list[FunctionSymbol]] = defaultdict(list)
    target_by_name: dict[str, list[FunctionSymbol]] = defaultdict(list)
    for function in source_functions:
        if function.section in CODE_SECTIONS:
            source_by_name[function.name].append(function)
            source_by_signature[
                (function.section, function_signature(source_dol, function))
            ].append(function)
    for function in target_functions:
        if function.section in CODE_SECTIONS:
            target_by_name[function.name].append(function)
            target_by_signature[
                (function.section, function_signature(target_dol, function))
            ].append(function)

    matches: dict[int, FunctionSymbol] = {}
    for signature, candidates in source_by_signature.items():
        targets = target_by_signature.get(signature, [])
        if len(candidates) == 1 and len(targets) == 1:
            matches[candidates[0].address] = targets[0]
    used_targets = {function.address for function in matches.values()}
    for name, candidates in source_by_name.items():
        targets = target_by_name.get(name, [])
        if len(candidates) != 1 or len(targets) != 1:
            continue
        source_function = candidates[0]
        target_function = targets[0]
        if (
            source_function.address in matches
            or target_function.address in used_targets
            or source_function.section != target_function.section
            or function_signature(source_dol, source_function)
            != function_signature(target_dol, target_function)
        ):
            continue
        matches[source_function.address] = target_function
        used_targets.add(target_function.address)
    return matches


def dol_section(dol: DolFile, section: str):
    index = SECTION_INDEX[section]
    return next(item for item in dol.sections if item.index == index)


def retail_sda_base(dol) -> int:
    """Read the unique lis r13 / ori r13 startup pair, without linked ELF hints."""
    section = dol_section(dol, "init")
    words = struct.unpack(f">{section.size // 4}I",
                          read_dol_range(dol, section.address, section.size))
    candidates = [((high & 0xFFFF) << 16) | (low & 0xFFFF)
                  for high, low in zip(words, words[1:])
                  if high & 0xFFFF0000 == 0x3DA00000
                  and low & 0xFFFF0000 == 0x61AD0000]
    if len(candidates) != 1:
        raise ValueError(f"Expected one retail r13 startup pair in {dol.path}")
    return candidates[0]


def sda_reference_pairs(source, source_functions, target, target_functions) -> dict:
    source_base, target_base = retail_sda_base(source), retail_sda_base(target)
    left, right = defaultdict(list), defaultdict(list)
    for dol, functions, signatures in ((source, source_functions, left),
                                        (target, target_functions, right)):
        for function in functions:
            if function.section in CODE_SECTIONS:
                signatures[(function.section, function_signature(dol, function))].append(function)
    pairs = {}
    for signature, functions in left.items():
        targets = right.get(signature, [])
        if len(functions) != 1 or len(targets) != 1:
            continue
        pairs[functions[0].address] = (functions[0], targets[0], "unique function")
    # Tiny setters and getters repeat. Their order is usable only when BOTH
    # enclosing functions are independently unique and the complete intervening
    # sequence has the same function count and instruction shapes.
    for section in CODE_SECTIONS:
        source_run = sorted((f for f in source_functions if f.section == section),
                            key=lambda f: f.address)
        target_run = sorted((f for f in target_functions if f.section == section),
                            key=lambda f: f.address)
        target_indices = {f.address: i for i, f in enumerate(target_run)}
        anchors = [i for i, f in enumerate(source_run) if f.address in pairs]
        for before, after in zip(anchors, anchors[1:]):
            first = target_indices[pairs[source_run[before].address][1].address]
            last = target_indices[pairs[source_run[after].address][1].address]
            if last - first != after - before or after - before < 2:
                continue
            a_run, b_run = source_run[before:after + 1], target_run[first:last + 1]
            if any(a.address + a.size != b.address
                   for run in (a_run, b_run) for a, b in zip(run, run[1:])):
                continue
            if not all(function_signature(source, a) == function_signature(target, b)
                       for a, b in zip(a_run, b_run)):
                continue
            for a, b in zip(a_run[1:-1], b_run[1:-1]):
                pairs[a.address] = (a, b, "unique enclosing functions")
    refs = defaultdict(lambda: defaultdict(list))
    for a, b, evidence in pairs.values():
        source_words = struct.unpack(f">{a.size // 4}I", read_dol_range(source, a.address, a.size))
        target_words = struct.unpack(f">{b.size // 4}I", read_dol_range(target, b.address, b.size))
        for offset, (x, y) in enumerate(zip(source_words, target_words)):
            # addi and non-updating scalar loads/stores. Updating r13 is not
            # an ABI small-data access; logical-immediate operands are unsigned.
            if x >> 26 not in {14, *range(32, 56, 2)} or (x >> 16) & 31 != 13:
                continue
            source_address = source_base + struct.unpack(">h", struct.pack(">H", x & 0xFFFF))[0]
            target_address = target_base + struct.unpack(">h", struct.pack(">H", y & 0xFFFF))[0]
            refs[source_address][target_address].append({
                "source_function": a.name, "target_function": b.name,
                "source_instruction": a.address + offset * 4,
                "target_instruction": b.address + offset * 4,
                "match_evidence": evidence,
            })
    return {address: dict(targets) for address, targets in refs.items()}


def sbss2_bounds(dol: DolFile) -> tuple[int, int] | None:
    """Bound the final zero-filled tail using the DOL header, not file bytes.

    SFA places .sbss2 immediately after .sdata2, ending at the aggregate BSS
    range's end. Reject truncated headers and layouts with initialized storage
    in that tail; neither provides this zero-section boundary evidence.
    """
    if len(dol.data) < 0xE0:
        return None
    bss_start, bss_size = struct.unpack_from(">II", dol.data, 0xD8)
    bss_end = bss_start + bss_size
    pool = dol_section(dol, "sdata2")
    start = pool.address + pool.size
    if not bss_start <= start < bss_end <= 0x100000000:
        return None
    if any(
        section.size and section.address < bss_end and start < section.address + section.size
        for section in dol.sections
    ):
        return None
    return start, bss_end


def normalized_section_words(dol: DolFile, section: str) -> tuple[object, list[int]]:
    dol_range = dol_section(dol, section)
    raw = dol.data[dol_range.offset : dol_range.offset + dol_range.size]
    words: list[int] = []
    for offset in range(0, len(raw), 4):
        chunk = raw[offset : offset + 4].ljust(4, b"\0")
        (word,) = struct.unpack(">I", chunk)
        if section in CODE_SECTIONS:
            word = mask_instruction(word)
        elif 0x80000000 <= word < 0x81800000:
            # Relocated pointers move with their targets between versions.  A
            # pointer marker retains the surrounding data shape without
            # pretending the absolute value is stable.
            word = 0xFFFFFFFF
        words.append(word)
    return dol_range, words


def build_boundary_map(
    section: str,
    boundaries: set[int],
    source_dol: DolFile,
    target_dol: DolFile,
    source_functions: list[FunctionSymbol],
    matches: dict[int, FunctionSymbol],
    target_all_symbol_span_index: dict[str, tuple[list[int], list[int]]],
) -> tuple[dict[int, int], dict[int, int]]:
    """Map split boundaries using direct binary anchors and stable corridors."""

    source_range, source_words = normalized_section_words(source_dol, section)
    target_range, target_words = normalized_section_words(target_dol, section)
    direct = {
        source_range.address: target_range.address,
        source_range.address
        + source_range.size: target_range.address
        + target_range.size,
    }

    if section in CODE_SECTIONS:
        source_by_address = {item.address: item for item in source_functions}
        for source_address, target_function in matches.items():
            source_function = source_by_address[source_address]
            if not (
                source_range.address
                <= source_address
                < source_range.address + source_range.size
            ):
                continue
            direct[source_address] = target_function.address
            direct[source_address + source_function.size] = (
                target_function.address + target_function.size
            )
    else:
        # Eight normalized words are long enough to make ordinary data
        # contexts unique while still surviving small localized edits.
        context_words = 8
        target_index: dict[int, int] = {}
        duplicate_hashes: set[int] = set()
        for index in range(len(target_words) - context_words + 1):
            signature = hash(tuple(target_words[index : index + context_words]))
            if signature in target_index:
                duplicate_hashes.add(signature)
            else:
                target_index[signature] = index

        for boundary in boundaries:
            if boundary in direct:
                continue
            source_index = (boundary - source_range.address) // 4
            byte_phase = (boundary - source_range.address) % 4
            candidates: list[int] = []
            if 0 <= source_index <= len(source_words) - context_words:
                source_context = source_words[
                    source_index : source_index + context_words
                ]
                signature = hash(tuple(source_context))
                target_index_value = target_index.get(signature)
                if (
                    target_index_value is not None
                    and signature not in duplicate_hashes
                    and source_context
                    == target_words[
                        target_index_value : target_index_value + context_words
                    ]
                    and not boundary_crosses_symbol(
                        target_all_symbol_span_index,
                        section,
                        target_range.address + target_index_value * 4 + byte_phase,
                    )
                ):
                    candidates.append(target_index_value)
            if context_words <= source_index <= len(source_words):
                source_context = source_words[
                    source_index - context_words : source_index
                ]
                signature = hash(tuple(source_context))
                target_index_value = target_index.get(signature)
                if (
                    target_index_value is not None
                    and signature not in duplicate_hashes
                    and source_context
                    == target_words[
                        target_index_value : target_index_value + context_words
                    ]
                    and not boundary_crosses_symbol(
                        target_all_symbol_span_index,
                        section,
                        target_range.address + (target_index_value + context_words) * 4 + byte_phase,
                    )
                ):
                    candidates.append(target_index_value + context_words)
            if candidates and len(set(candidates)) == 1:
                # Word contexts locate the containing word, not necessarily
                # the boundary itself: packed strings and halfwords may end
                # one, two, or three bytes into that word.
                direct[boundary] = target_range.address + candidates[0] * 4 + byte_phase

    # Discard the rare repeated-code anchor that would make the global mapping
    # run backwards.  Source and target object order is otherwise preserved.
    monotonic: dict[int, int] = {}
    previous_target = -1
    for source_address, target_address in sorted(direct.items()):
        if target_address > previous_target:
            monotonic[source_address] = target_address
            previous_target = target_address
    direct = monotonic

    inferred = dict(direct)
    direct_addresses = sorted(direct)
    for boundary in sorted(boundaries):
        if boundary in inferred:
            continue
        index = bisect.bisect_left(direct_addresses, boundary)
        if index == 0 or index == len(direct_addresses):
            continue
        before = direct_addresses[index - 1]
        after = direct_addresses[index]
        before_delta = direct[before] - before
        after_delta = direct[after] - after
        if before_delta == after_delta:
            target_boundary = boundary + before_delta
            # Context anchors can sit inside strings or packed byte tables and
            # therefore change phase across versions.  Inferred object
            # boundaries retain their source word phase; otherwise an aligned
            # EN symbol can be projected to a halfword address between two
            # unaligned string anchors.
            target_boundary += (boundary - target_boundary) % 4
            inferred[boundary] = target_boundary

    # Localized strings and tables can change the delta on either side of a
    # boundary.  Interpolate the remaining address within its two direct
    # anchors, then let target-symbol and overlap validation decide whether the
    # resulting TU is safe to claim.
    for boundary in sorted(boundaries):
        if boundary in inferred:
            continue
        index = bisect.bisect_left(direct_addresses, boundary)
        if index == 0 or index == len(direct_addresses):
            continue
        before = direct_addresses[index - 1]
        after = direct_addresses[index]
        source_width = after - before
        target_width = direct[after] - direct[before]
        if source_width <= 0 or target_width <= 0:
            continue
        source_offset = boundary - before
        target_boundary = direct[before] + round(
            source_offset * target_width / source_width
        )
        target_boundary += (boundary - target_boundary) % 4
        if direct[before] < target_boundary < direct[after]:
            inferred[boundary] = target_boundary
    return direct, inferred


def build_all_boundary_maps(
    source_splits: list[SplitRange],
    source_dol: DolFile,
    target_dol: DolFile,
    source_functions: list[FunctionSymbol],
    matches: dict[int, FunctionSymbol],
    target_all_symbol_span_index: dict[str, tuple[list[int], list[int]]],
) -> tuple[dict[str, dict[int, int]], dict[str, tuple[int, int]]]:
    boundaries_by_section: dict[str, set[int]] = defaultdict(set)
    for split in source_splits:
        boundaries_by_section[split.section].update((split.start, split.end))

    result: dict[str, dict[int, int]] = {}
    anchor_counts: dict[str, tuple[int, int]] = {}
    for section in SECTION_INDEX:
        boundaries = boundaries_by_section.get(section)
        if not boundaries:
            continue
        direct, inferred = build_boundary_map(
            section,
            boundaries,
            source_dol,
            target_dol,
            source_functions,
            matches,
            target_all_symbol_span_index,
        )
        result[section] = inferred
        anchor_counts[section] = (
            sum(boundary in direct for boundary in boundaries),
            sum(boundary in inferred for boundary in boundaries),
        )

    # Retain the existing large-BSS origin projection. Small BSS is handled
    # separately with retail SDA operands: equal section widths do not imply
    # equal internal layout, particularly in PAL and EN rev1.
    zero_section_origins = {
        "bss": (
            dol_section(source_dol, "data").address
            + dol_section(source_dol, "data").size,
            dol_section(target_dol, "data").address
            + dol_section(target_dol, "data").size,
        ),
    }
    for section, (source_origin, target_origin) in zero_section_origins.items():
        boundaries = boundaries_by_section.get(section)
        if not boundaries:
            continue
        delta = target_origin - source_origin
        result[section] = {boundary: boundary + delta for boundary in boundaries}
        anchor_counts[section] = (0, len(boundaries))

    boundaries = boundaries_by_section.get("sbss2")
    if boundaries:
        source_bounds = sbss2_bounds(source_dol)
        target_bounds = sbss2_bounds(target_dol)
        mapped = {}
        if (
            source_bounds is not None
            and target_bounds is not None
            and source_bounds[1] - source_bounds[0] == target_bounds[1] - target_bounds[0]
        ):
            delta = target_bounds[0] - source_bounds[0]
            mapped = {
                boundary: boundary + delta for boundary in boundaries
                if source_bounds[0] <= boundary <= source_bounds[1]
            }
        result["sbss2"] = mapped
        anchor_counts["sbss2"] = (0, len(mapped))
    return result, anchor_counts


def load_symbol_spans(path: Path) -> dict[str, tuple[SymbolSpan, ...]]:
    return parse_symbol_spans(path.read_text(encoding="utf-8"))


def parse_symbol_spans(text: str) -> dict[str, tuple[SymbolSpan, ...]]:
    spans: dict[str, list[SymbolSpan]] = defaultdict(list)
    size_re = re.compile(r"\bsize:0x([0-9A-Fa-f]+)\b")
    for line in text.splitlines():
        match = SYMBOL_LINE_RE.match(line)
        size_match = size_re.search(line)
        if match is None or size_match is None:
            continue
        start = int(match.group(3), 16)
        size = int(size_match.group(1), 16)
        if size:
            spans[match.group(2)].append(
                SymbolSpan(match.group(1), match.group(2), start, start + size)
            )
    return {
        section: tuple(sorted(section_spans, key=lambda span: (span.start, span.end)))
        for section, section_spans in spans.items()
    }


def symbol_span_index(
    spans: dict[str, tuple[SymbolSpan, ...]],
    *,
    include_address_symbols: bool = False,
) -> dict[str, tuple[list[int], list[int]]]:
    result: dict[str, tuple[list[int], list[int]]] = {}
    for section, section_spans in spans.items():
        starts: list[int] = []
        prefix_max_end: list[int] = []
        maximum = 0
        for span in section_spans:
            if (
                not include_address_symbols
                and ADDRESS_SYMBOL_RE.match(span.name) is not None
            ):
                continue
            starts.append(span.start)
            maximum = max(maximum, span.end)
            prefix_max_end.append(maximum)
        result[section] = (starts, prefix_max_end)
    return result


def load_symbol_span_index(
    path: Path,
    *,
    include_address_symbols: bool = False,
) -> dict[str, tuple[list[int], list[int]]]:
    return symbol_span_index(
        load_symbol_spans(path),
        include_address_symbols=include_address_symbols,
    )


def boundary_crosses_symbol(
    span_index: dict[str, tuple[list[int], list[int]]],
    section: str,
    boundary: int,
) -> bool:
    starts, prefix_max_end = span_index.get(section, ([], []))
    index = bisect.bisect_left(starts, boundary) - 1
    return index >= 0 and prefix_max_end[index] > boundary


def normalized_span_signature(dol: DolFile, span: SymbolSpan) -> bytes:
    """Return span bytes with relocatable DOL pointers normalized."""

    raw = bytearray(read_dol_range(dol, span.start, span.size))
    for offset in range((-span.start) % 4, len(raw) - 3, 4):
        (word,) = struct.unpack_from(">I", raw, offset)
        if span.section in CODE_SECTIONS:
            struct.pack_into(">I", raw, offset, mask_instruction(word))
        elif 0x80000000 <= word < 0x81800000:
            struct.pack_into(">I", raw, offset, 0xFFFFFFFF)
    return bytes(raw)


def weak_symbol_name(name: str) -> bool:
    return (
        ADDRESS_SYMBOL_RE.match(name) is not None
        or re.match(r"^@\d+$", name) is not None
    )


def direct_text_xrefs_into_range(dol: DolFile, start: int, end: int) -> set[int]:
    """Return text addresses that directly materialize a pointer into a range."""

    xrefs: set[int] = set()
    for section in dol.text_sections:
        words = [
            struct.unpack_from(">I", dol.data, section.offset + offset)[0]
            for offset in range(0, section.size, 4)
        ]
        for index, first_word in enumerate(words):
            if first_word >> 26 != 15 or (first_word >> 16) & 31:
                continue
            register = (first_word >> 21) & 31
            high = first_word & 0xFFFF
            for next_index in range(index + 1, min(index + 6, len(words))):
                second_word = words[next_index]
                opcode = second_word >> 26
                base = (second_word >> 16) & 31
                target: int | None = None
                if opcode == 14 and base == register:
                    signed_high = high - 0x10000 if high & 0x8000 else high
                    low = second_word & 0xFFFF
                    signed_low = low - 0x10000 if low & 0x8000 else low
                    target = ((signed_high << 16) + signed_low) & 0xFFFFFFFF
                elif (
                    opcode == 24
                    and base == register
                    and (second_word >> 21) & 31 == register
                ):
                    target = ((high << 16) | (second_word & 0xFFFF)) & 0xFFFFFFFF
                if target is not None and start <= target < end:
                    xrefs.add(section.address + index * 4)
    return xrefs


def snap_symbol_boundaries(
    source_splits: list[SplitRange],
    boundary_maps: dict[str, dict[int, int]],
    source_dol: DolFile,
    target_dol: DolFile,
    source_spans: dict[str, tuple[SymbolSpan, ...]],
    target_spans: dict[str, tuple[SymbolSpan, ...]],
    target_symbol_span_index: dict[str, tuple[list[int], list[int]]],
    target_all_symbol_span_index: dict[str, tuple[list[int], list[int]]],
) -> tuple[dict[str, dict[int, int]], int]:
    """Snap rejected inferred boundaries to proven homologous symbol edges."""

    splits_by_boundary: dict[tuple[str, int], list[SplitRange]] = defaultdict(list)
    for split in source_splits:
        splits_by_boundary[(split.section, split.start)].append(split)
        splits_by_boundary[(split.section, split.end)].append(split)

    target_text_ranges_by_unit: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for split in source_splits:
        if split.section not in CODE_SECTIONS or split.start == split.end:
            continue
        section_map = boundary_maps.get(split.section, {})
        target_start = section_map.get(split.start)
        target_end = section_map.get(split.end)
        if target_start is not None and target_end is not None:
            target_text_ranges_by_unit[split.unit].append((target_start, target_end))

    proposals: dict[tuple[str, int], int] = {}
    for section, section_map in boundary_maps.items():
        if section in ZERO_SECTIONS:
            # Zero-filled storage has no byte signatures to prove a new edge.
            # Keep the inferred boundary; a crossing symbol will reject its TU.
            continue
        section_source_spans = source_spans.get(section, ())
        section_target_spans = target_spans.get(section, ())
        source_chain_signatures: list[bytes] = []
        target_chain_signatures: list[bytes] = []
        target_chains: dict[int, dict[tuple[tuple[int, bytes], ...], list[int]]] = {}
        if section in CODE_SECTIONS or section == "data":
            source_chain_signatures = [
                normalized_span_signature(source_dol, span)
                for span in section_source_spans
            ]
            target_chain_signatures = [
                normalized_span_signature(target_dol, span)
                for span in section_target_spans
            ]
            for length in range(2, 7):
                chain_index: dict[
                    tuple[tuple[int, bytes], ...], list[int]
                ] = defaultdict(list)
                for start in range(len(section_target_spans) - length + 1):
                    chain = section_target_spans[start : start + length]
                    if any(
                        before.end != after.start
                        for before, after in zip(chain, chain[1:])
                    ):
                        continue
                    key = tuple(
                        (span.size, target_chain_signatures[start + offset])
                        for offset, span in enumerate(chain)
                    )
                    chain_index[key].append(start)
                target_chains[length] = chain_index
        for source_boundary, target_boundary in section_map.items():
            touching = splits_by_boundary.get((section, source_boundary), [])
            currently_rejected = False
            for split in touching:
                target_start = section_map.get(split.start)
                target_end = section_map.get(split.end)
                if target_start is None or target_end is None:
                    continue
                size_drift = split.end - split.start != target_end - target_start
                index = (
                    target_all_symbol_span_index
                    if size_drift
                    else target_symbol_span_index
                )
                if boundary_crosses_symbol(index, section, target_boundary):
                    currently_rejected = True
                    break
            if not currently_rejected:
                continue

            if section in CODE_SECTIONS or section == "data":
                chain_candidates: list[tuple[str, int, int, int]] = []
                for side in ("before", "after"):
                    anchors = [
                        index
                        for index, span in enumerate(section_source_spans)
                        if (
                            span.end == source_boundary
                            if side == "before"
                            else span.start == source_boundary
                        )
                    ]
                    if len(anchors) != 1:
                        continue
                    anchor = anchors[0]
                    for length in range(2, 7):
                        start = anchor - length + 1 if side == "before" else anchor
                        if start < 0 or start + length > len(section_source_spans):
                            continue
                        chain = section_source_spans[start : start + length]
                        if any(
                            before.end != after.start
                            for before, after in zip(chain, chain[1:])
                        ):
                            continue
                        total_size = sum(span.size for span in chain)
                        if total_size < 32:
                            continue
                        key = tuple(
                            (span.size, source_chain_signatures[start + offset])
                            for offset, span in enumerate(chain)
                        )
                        matches = target_chains[length].get(key, [])
                        if len(matches) != 1:
                            continue
                        target_start = matches[0]
                        candidate = (
                            section_target_spans[target_start + length - 1].end
                            if side == "before"
                            else section_target_spans[target_start].start
                        )
                        chain_candidates.append((side, length, total_size, candidate))
                if chain_candidates:
                    side_candidates: dict[str, int] = {}
                    for side in ("before", "after"):
                        candidates = [
                            (length, total_size, candidate)
                            for (
                                candidate_side,
                                length,
                                total_size,
                                candidate,
                            ) in chain_candidates
                            if candidate_side == side
                        ]
                        if not candidates:
                            continue
                        best_strength = max(
                            (length, total_size) for length, total_size, _ in candidates
                        )
                        best_candidates = {
                            candidate
                            for length, total_size, candidate in candidates
                            if (length, total_size) == best_strength
                        }
                        if len(best_candidates) == 1:
                            side_candidates[side] = best_candidates.pop()
                    if len(set(side_candidates.values())) == 1:
                        proposals[(section, source_boundary)] = next(
                            iter(side_candidates.values())
                        )
                        continue
                    # A later binary may insert TU-owned initialized data at a
                    # boundary while leaving exact symbol chains on both
                    # sides.  Attach that corridor to the preceding TU only
                    # when all direct code references into it originate from
                    # that TU's projected text.  Otherwise preserve the
                    # disagreement and leave both units unclaimed.
                    if (
                        section == "data"
                        and set(side_candidates) == {"before", "after"}
                        and side_candidates["before"] < side_candidates["after"]
                    ):
                        preceding_units = {
                            split.unit
                            for split in touching
                            if split.end == source_boundary and split.start < split.end
                        }
                        following_units = {
                            split.unit
                            for split in touching
                            if split.start == source_boundary
                            and split.start < split.end
                        }
                        if (
                            len(preceding_units) == 1
                            and len(following_units) == 1
                            and preceding_units != following_units
                        ):
                            preceding_unit = next(iter(preceding_units))
                            xrefs = direct_text_xrefs_into_range(
                                target_dol,
                                side_candidates["before"],
                                side_candidates["after"],
                            )
                            text_ranges = target_text_ranges_by_unit.get(
                                preceding_unit, []
                            )
                            if xrefs and all(
                                any(start <= xref < end for start, end in text_ranges)
                                for xref in xrefs
                            ):
                                proposals[(section, source_boundary)] = side_candidates[
                                    "after"
                                ]
                                continue
                if section in CODE_SECTIONS:
                    continue

            crossing = [
                span
                for span in section_target_spans
                if span.start < target_boundary < span.end
            ]
            candidates: list[int] = []
            target_span: SymbolSpan | None = None
            if len(crossing) == 1:
                target_span = crossing[0]
                target_signature = normalized_span_signature(target_dol, target_span)
                named_homolog = any(
                    source_span.name == target_span.name
                    and (
                        source_span.start == source_boundary
                        or source_span.end == source_boundary
                    )
                    for source_span in section_source_spans
                )
                weak_zero_extended_tail = any(
                    weak_symbol_name(source_span.name)
                    and source_span.end == source_boundary
                    and 0 < target_span.size - source_span.size <= 8
                    and target_signature[: source_span.size]
                    == normalized_span_signature(source_dol, source_span)
                    and not any(target_signature[source_span.size :])
                    for source_span in section_source_spans
                )
                if (
                    weak_symbol_name(target_span.name)
                    or named_homolog
                    or weak_zero_extended_tail
                ):
                    for source_span in section_source_spans:
                        source_signature = normalized_span_signature(
                            source_dol, source_span
                        )
                        if source_span.end == source_boundary:
                            candidate = target_span.end
                        elif source_span.start == source_boundary:
                            candidate = target_span.start
                        else:
                            continue
                        exact = (
                            source_span.size == target_span.size
                            and source_signature == target_signature
                        )
                        zero_extended_tail = (
                            candidate == target_span.end
                            and 0 < target_span.size - source_span.size <= 8
                            and target_signature[: source_span.size] == source_signature
                            and not any(target_signature[source_span.size :])
                        )
                        if exact or zero_extended_tail:
                            candidates.append(candidate)

            # Interpolation can land inside the symbol after the real TU edge.
            # When one complete source symbol touching that edge has exactly one
            # normalized target homolog, its corresponding edge is stronger
            # evidence than the inferred address.
            if not candidates:
                exact_matches: list[int] = []
                for source_span in section_source_spans:
                    if (
                        source_span.end != source_boundary
                        or source_span.size < 32
                        or weak_symbol_name(source_span.name)
                    ):
                        continue
                    source_signature = normalized_span_signature(
                        source_dol, source_span
                    )
                    for homolog in section_target_spans:
                        if (
                            source_span.size == homolog.size
                            and source_signature
                            == normalized_span_signature(target_dol, homolog)
                        ):
                            exact_matches.append(homolog.end)
                if len(exact_matches) == 1:
                    candidates = exact_matches
            if len(set(candidates)) == 1:
                candidate = candidates[0]
                proposals[(section, source_boundary)] = candidate
                # The source may leave a short zero alignment tail after the
                # symbol while the target folds that tail into an expanded
                # object.  Move the following boundary with the proven edge.
                if target_span is not None and candidate == target_span.end:
                    ordered_source = sorted(section_map)
                    boundary_index = bisect.bisect_right(
                        ordered_source, source_boundary
                    )
                    if boundary_index < len(ordered_source):
                        following = ordered_source[boundary_index]
                        following_target = section_map[following]
                        if (
                            0 < following - source_boundary <= 7
                            and target_boundary < following_target < target_span.end
                            and gap_is_zero(
                                source_dol, section, source_boundary, following
                            )
                            and not symbol_overlaps_range(
                                source_spans,
                                section,
                                source_boundary,
                                following,
                                semantic_only=True,
                            )
                        ):
                            proposals[(section, following)] = candidate

    snapped = {
        section: dict(section_map) for section, section_map in boundary_maps.items()
    }
    applied = 0
    proposal_groups: dict[tuple[str, int], dict[int, int]] = defaultdict(dict)
    for (section, source_boundary), candidate in proposals.items():
        proposal_groups[(section, candidate)][source_boundary] = candidate
    for (section, _), section_proposals in sorted(proposal_groups.items()):
        trial = dict(snapped[section])
        trial.update(section_proposals)
        ordered = [target for _, target in sorted(trial.items())]
        if any(before > after for before, after in zip(ordered, ordered[1:])):
            continue
        valid = True
        for split in source_splits:
            if split.section != section or split.start == split.end:
                continue
            target_start = trial.get(split.start)
            target_end = trial.get(split.end)
            if (
                target_start is not None
                and target_end is not None
                and target_start >= target_end
            ):
                valid = False
                break
        if valid:
            snapped[section] = trial
            applied += len(section_proposals)
    return snapped, applied


def gap_is_zero(dol: DolFile, section: str, start: int, end: int) -> bool:
    if section in ZERO_SECTIONS:
        return True
    return not any(read_dol_range(dol, start, end - start))


def symbol_overlaps_range(
    spans: dict[str, tuple[SymbolSpan, ...]],
    section: str,
    start: int,
    end: int,
    *,
    semantic_only: bool = False,
) -> bool:
    return any(
        span.start < end
        and start < span.end
        and (not semantic_only or not weak_symbol_name(span.name))
        for span in spans.get(section, ())
    )


def port_coherent_units(
    source_splits: list[SplitRange],
    source_functions: list[FunctionSymbol],
    target_functions: list[FunctionSymbol],
    boundary_maps: dict[str, dict[int, int]],
    target_symbol_spans: dict[str, tuple[list[int], list[int]]],
    target_all_symbol_spans: dict[str, tuple[list[int], list[int]]],
    source_dol: DolFile,
    target_dol: DolFile,
    source_detailed_spans: dict[str, tuple[SymbolSpan, ...]],
    target_detailed_spans: dict[str, tuple[SymbolSpan, ...]],
) -> tuple[list[PortedRange], dict[str, int], int, int, dict[str, tuple[str, ...]]]:
    source_by_section: dict[str, list[FunctionSymbol]] = defaultdict(list)
    target_by_section: dict[str, list[FunctionSymbol]] = defaultdict(list)
    for function in source_functions:
        source_by_section[function.section].append(function)
    for function in target_functions:
        target_by_section[function.section].append(function)

    by_unit: dict[str, list[SplitRange]] = defaultdict(list)
    for split in source_splits:
        by_unit[split.unit].append(split)

    target_exact_span_index: dict[
        str, dict[tuple[int, bytes], list[SymbolSpan]]
    ] = defaultdict(lambda: defaultdict(list))
    for section, spans in target_detailed_spans.items():
        if section in CODE_SECTIONS or section in ZERO_SECTIONS:
            continue
        for span in spans:
            try:
                signature = normalized_span_signature(target_dol, span)
            except ValueError:
                continue
            target_exact_span_index[section][(span.size, signature)].append(span)

    source_exact_split_spans: dict[tuple[str, str, int], tuple[SymbolSpan, bytes]] = {}
    exact_splits_by_section: dict[
        str, list[tuple[SplitRange, SymbolSpan, bytes]]
    ] = defaultdict(list)
    for split in source_splits:
        if (
            split.start == split.end
            or split.section in CODE_SECTIONS
            or split.section in ZERO_SECTIONS
        ):
            continue
        exact_spans = [
            span
            for span in source_detailed_spans.get(split.section, ())
            if span.start == split.start and span.end == split.end
        ]
        if len(exact_spans) != 1:
            continue
        span = exact_spans[0]
        signature = normalized_span_signature(source_dol, span)
        key = (split.unit, split.section, split.start)
        source_exact_split_spans[key] = (span, signature)
        exact_splits_by_section[split.section].append((split, span, signature))

    # Individual descriptor shapes are often repeated.  A contiguous sequence
    # of complete split-owned symbols can still be globally unique, proving the
    # per-split ranges on either side of a target-only insertion.
    exact_chain_overrides: dict[tuple[str, str, int], SymbolSpan] = {}
    for section, entries in exact_splits_by_section.items():
        entries.sort(key=lambda item: item[0].start)
        runs: list[list[tuple[SplitRange, SymbolSpan, bytes]]] = []
        run: list[tuple[SplitRange, SymbolSpan, bytes]] = []
        for entry in entries:
            if run and run[-1][0].end != entry[0].start:
                runs.append(run)
                run = []
            run.append(entry)
        if run:
            runs.append(run)
        target_spans = target_detailed_spans.get(section, ())
        target_signatures: list[bytes | None] = []
        for span in target_spans:
            try:
                target_signatures.append(normalized_span_signature(target_dol, span))
            except ValueError:
                target_signatures.append(None)
        for run in runs:
            for length in range(len(run), 1, -1):
                for run_start in range(len(run) - length + 1):
                    chain = run[run_start : run_start + length]
                    keys = [(item[0].unit, section, item[0].start) for item in chain]
                    if any(key in exact_chain_overrides for key in keys):
                        continue
                    matches: list[tuple[SymbolSpan, ...]] = []
                    for target_start in range(len(target_spans) - length + 1):
                        homologs = target_spans[target_start : target_start + length]
                        if any(
                            before.end != after.start
                            for before, after in zip(homologs, homologs[1:])
                        ):
                            continue
                        if all(
                            source_span.size == target_span.size
                            and source_signature
                            == target_signatures[target_start + index]
                            for index, (
                                (_, source_span, source_signature),
                                target_span,
                            ) in enumerate(zip(chain, homologs))
                        ):
                            matches.append(homologs)
                    if len(matches) == 1:
                        for key, homolog in zip(keys, matches[0]):
                            exact_chain_overrides[key] = homolog

    rejected: dict[str, int] = defaultdict(int)
    rejected_units: dict[str, set[str]] = defaultdict(set)
    exact_symbol_range_remaps = 0
    accepted: list[PortedRange] = []
    for unit, ranges in by_unit.items():
        candidates: list[PortedRange] = []
        reason: str | None = None
        for split in ranges:
            if split.start == split.end:
                continue
            section_map = boundary_maps.get(split.section, {})
            target_start = section_map.get(split.start)
            target_end = section_map.get(split.end)
            if target_start is None or target_end is None:
                reason = "unmapped section boundary"
                break
            if target_start >= target_end:
                reason = "invalid target range"
                break
            source_size = split.end - split.start
            target_size = target_end - target_start
            if split.section not in CODE_SECTIONS and split.section not in ZERO_SECTIONS:
                key = (split.unit, split.section, split.start)
                chain_homolog = exact_chain_overrides.get(key)
                source_exact = source_exact_split_spans.get(key)
                if chain_homolog is not None:
                    target_exact_spans = [chain_homolog]
                elif source_exact is not None:
                    source_span, signature = source_exact
                    local_homologs = [
                        span
                        for span in target_detailed_spans.get(split.section, ())
                        if span.start == target_start
                        and span.end == target_start + source_span.size
                        and normalized_span_signature(target_dol, span) == signature
                    ]
                    if len(local_homologs) == 1:
                        target_exact_spans = local_homologs
                    elif source_span.size < 8:
                        # A normalized relocated pointer is just one generic
                        # marker.  If target analysis did not name the symbol
                        # at the already-mapped boundary, a different named
                        # pointer elsewhere is not evidence for moving it.
                        target_exact_spans = []
                    else:
                        target_exact_spans = target_exact_span_index.get(
                            split.section, {}
                        ).get((source_span.size, signature), [])
                else:
                    target_exact_spans = []
                if len(target_exact_spans) == 1:
                    homolog = target_exact_spans[0]
                    if target_start != homolog.start or target_end != homolog.end:
                        exact_symbol_range_remaps += 1
                    target_start = homolog.start
                    target_end = homolog.end
                    target_size = source_size
            size_drift = source_size != target_size
            spans = (
                target_all_symbol_spans
                if size_drift or split.section in CODE_SECTIONS
                else target_symbol_spans
            )
            if boundary_crosses_symbol(
                spans, split.section, target_start
            ) or boundary_crosses_symbol(spans, split.section, target_end):
                reason = "target symbol crosses boundary"
                break
            target_split = SplitRange(
                split.unit, split.section, target_start, target_end
            )
            candidates.append(
                PortedRange(
                    source=split,
                    target_start=target_start,
                    target_end=target_end,
                    source_functions=functions_in_range(source_by_section, split),
                    target_functions=functions_in_range(
                        target_by_section, target_split
                    ),
                )
            )
        if reason is not None:
            rejected[reason] += 1
            rejected_units[reason].add(unit)
            continue
        accepted.extend(candidates)

    # Retain short, invariant, zero-filled alignment gaps outside both objects.
    # decomp-toolkit lets the linker provide these bytes; extending an object
    # section instead changes its size and can absorb padding into its last symbol.
    alignment_gaps: set[tuple[str, int, int]] = set()
    next_source_range: dict[tuple[str, str, int], SplitRange] = {}
    source_ranges_by_section: dict[str, list[SplitRange]] = defaultdict(list)
    for split in source_splits:
        if split.start != split.end:
            source_ranges_by_section[split.section].append(split)
    for section, ranges in source_ranges_by_section.items():
        ranges.sort(key=lambda item: item.start)
        for before, after in zip(ranges, ranges[1:]):
            next_source_range[(before.unit, section, before.start)] = after
    for before in accepted:
        section = before.source.section
        after = next_source_range.get(
            (before.source.unit, section, before.source.start)
        )
        if after is None:
            continue
        target_after_start = boundary_maps.get(section, {}).get(after.start)
        if target_after_start is None:
            continue
        source_gap = after.start - before.source.end
        target_gap = target_after_start - before.target_end
        if not (0 < source_gap == target_gap <= 7):
            continue
        if symbol_overlaps_range(
            source_detailed_spans,
            section,
            before.source.end,
            after.start,
            semantic_only=True,
        ) or symbol_overlaps_range(
            target_detailed_spans,
            section,
            before.target_end,
            target_after_start,
            semantic_only=True,
        ):
            continue
        if not gap_is_zero(
            source_dol, section, before.source.end, after.start
        ) or not gap_is_zero(
            target_dol, section, before.target_end, target_after_start
        ):
            continue
        alignment_gaps.add((section, before.target_end, target_after_start))

    # Unknown corridors need word-aligned auto units. Proven alignment gaps
    # between accepted neighbors need no auto unit; a rejected neighbor must
    # not make a wider unknown corridor inherit that exemption.
    while True:
        reject_units: set[str] = set()
        by_section: dict[str, list[PortedRange]] = defaultdict(list)
        for item in accepted:
            by_section[item.source.section].append(item)
        for ranges in by_section.values():
            ranges.sort(key=lambda item: item.target_start)
            if ranges[-1].source.section == "sbss2":
                bounds = sbss2_bounds(target_dol)
                if (
                    bounds is not None
                    and ranges[-1].target_end < bounds[1]
                    and ranges[-1].target_end % 4
                ):
                    # The final unknown BSS corridor also needs an aligned
                    # auto unit; there is no claimed neighbor to prove a gap.
                    reject_units.add(ranges[-1].source.unit)
            for before, after in zip(ranges, ranges[1:]):
                if before.target_end >= after.target_start:
                    continue
                gap = (before.source.section, before.target_end, after.target_start)
                if gap in alignment_gaps:
                    continue
                if before.target_end % 4:
                    reject_units.add(before.source.unit)
                if after.target_start % 4:
                    reject_units.add(after.source.unit)
        if not reject_units:
            break
        rejected["unaligned auto-unit boundary"] += len(reject_units)
        rejected_units["unaligned auto-unit boundary"].update(reject_units)
        accepted = [item for item in accepted if item.source.unit not in reject_units]

    # Preserve the legacy treatment of remaining four-byte corridors, but do
    # not extend an object across an invariant gap proven outside the source TU.
    extensions: dict[tuple[str, str, int], int] = {}
    by_section = defaultdict(list)
    for item in accepted:
        by_section[item.source.section].append(item)
    for ranges in by_section.values():
        ranges.sort(key=lambda item: item.target_start)
        for before, after in zip(ranges, ranges[1:]):
            gap = (before.source.section, before.target_end, after.target_start)
            if after.target_start - before.target_end == 4 and gap not in alignment_gaps:
                extensions[
                    (
                        before.source.unit,
                        before.source.section,
                        before.source.start,
                    )
                ] = after.target_start
    accepted = [
        replace(
            item,
            target_end=extensions.get(
                (item.source.unit, item.source.section, item.source.start),
                item.target_end,
            ),
        )
        for item in accepted
    ]

    # Every initialized range and the final zero tail must stay in bounds after
    # boundary inference and padding folding.  A near-end corridor can retain
    # the source revision's trailing padding even when the target revision
    # removed it; reject the complete TU instead of emitting an invalid split.
    target_section_bounds = {
        section: (
            target_range.address,
            target_range.address + target_range.size,
        )
        for section in SECTION_INDEX
        for target_range in (dol_section(target_dol, section),)
    }
    if any(item.source.section == "sbss2" for item in accepted):
        target_section_bounds["sbss2"] = sbss2_bounds(target_dol) or (0, 0)
    out_of_bounds_units = {
        item.source.unit
        for item in accepted
        if item.source.section in target_section_bounds
        and not (
            target_section_bounds[item.source.section][0] <= item.target_start
            and item.target_end <= target_section_bounds[item.source.section][1]
        )
    }
    if out_of_bounds_units:
        rejected["target range outside section"] += len(out_of_bounds_units)
        rejected_units["target range outside section"].update(out_of_bounds_units)
        accepted = [
            item for item in accepted if item.source.unit not in out_of_bounds_units
        ]

    # Distinct source boundaries can collapse onto one target boundary when a
    # revision removes alignment padding or a tiny section entry.  Neither TU
    # is safe to claim in that case: reject every unit participating in the
    # overlap and let decomp-toolkit retain the target bytes in an autogenerated
    # range.  Repeat because removing one multi-section TU can expose another
    # conflict elsewhere.
    while True:
        overlapping_units: set[str] = set()
        by_section = defaultdict(list)
        for item in accepted:
            by_section[item.source.section].append(item)
        for ranges in by_section.values():
            ranges.sort(key=lambda item: (item.target_start, item.target_end))
            previous: PortedRange | None = None
            for item in ranges:
                if previous is not None and item.target_start < previous.target_end:
                    overlapping_units.add(previous.source.unit)
                    overlapping_units.add(item.source.unit)
                    if item.target_end > previous.target_end:
                        previous = item
                else:
                    previous = item
        if not overlapping_units:
            break
        rejected["overlapping projected ranges"] += len(overlapping_units)
        rejected_units["overlapping projected ranges"].update(overlapping_units)
        accepted = [
            item for item in accepted if item.source.unit not in overlapping_units
        ]

    # A coherent projection must never assign the same target bytes twice.
    previous_end: dict[str, int] = {}
    preserved_alignment_gaps = 0
    for split in sorted(
        accepted, key=lambda item: (item.source.section, item.target_start)
    ):
        if split.target_start < previous_end.get(split.source.section, 0):
            raise ValueError(
                f"Projected {split.source.unit} overlaps a prior "
                f"{split.source.section} range at 0x{split.target_start:08X}"
            )
        gap = (
            split.source.section,
            previous_end.get(split.source.section, 0),
            split.target_start,
        )
        preserved_alignment_gaps += gap in alignment_gaps
        previous_end[split.source.section] = split.target_end
    return (
        accepted,
        dict(sorted(rejected.items())),
        preserved_alignment_gaps,
        exact_symbol_range_remaps,
        {
            reason: tuple(sorted(units))
            for reason, units in sorted(rejected_units.items())
        },
    )


def paired_functions(
    split: PortedRange, matches: dict[int, FunctionSymbol]
) -> list[tuple[FunctionSymbol, FunctionSymbol]]:
    """Pair a coherent code range without letting one insertion hide other names.

    Unequal function counts forbid whole-range ordinal pairing. Unique binary
    anchors can still bound equal-count interior runs. Do not extrapolate past
    the first/last anchor or pair across reordered anchors or unequal runs.
    """
    if split.source.section not in CODE_SECTIONS:
        return []
    source, target = split.source_functions, split.target_functions
    if len(source) == len(target):
        return list(zip(source, target))
    target_indices = {function.address: index for index, function in enumerate(target)}
    anchors = [
        (index, target_indices[match.address])
        for index, function in enumerate(source)
        if (match := matches.get(function.address)) is not None
        and match.address in target_indices
    ]
    pairs = {index: target_index for index, target_index in anchors}
    if all(left[1] < right[1] for left, right in zip(anchors, anchors[1:])):
        for (left_source, left_target), (right_source, right_target) in zip(
            anchors, anchors[1:]
        ):
            if right_source - left_source == right_target - left_target:
                for offset in range(1, right_source - left_source):
                    pairs[left_source + offset] = left_target + offset
    return [
        (source[index], target[target_index])
        for index, target_index in sorted(pairs.items())
    ]


def build_symbol_mappings(
    ported: list[PortedRange], matches: dict[int, FunctionSymbol]
) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for split in ported:
        mappings: dict[str, str] = {}
        target_names: set[str] = set()
        source_names: set[str] = set()
        function_pairs = paired_functions(split, matches)
        for source_function, target_function in function_pairs:
            if (
                target_function.name in target_names
                or source_function.name in source_names
            ):
                continue
            target_names.add(target_function.name)
            source_names.add(source_function.name)
            if target_function.name != source_function.name:
                mappings[target_function.name] = source_function.name
        if mappings:
            result.setdefault(split.source.unit, {}).update(mappings)
    return dict(sorted(result.items()))


def render_splits(header: list[str], ported: list[PortedRange]) -> str:
    by_unit: dict[str, list[PortedRange]] = {}
    for split in ported:
        by_unit.setdefault(split.source.unit, []).append(split)
    lines = [*header, ""]
    for unit, ranges in by_unit.items():
        lines.append(f"{unit}:")
        for split in ranges:
            section = split.source.section
            if section not in {"extab", "extabindex"}:
                section = f".{section}"
            lines.append(
                f"\t{section:<11} "
                f"start:0x{split.target_start:08X} end:0x{split.target_end:08X}"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


SYMBOL_LINE_RE = re.compile(r"^(\S+)\s+=\s+\.?([^:]+):0x([0-9A-Fa-f]+);(.*)$")
ADDRESS_SYMBOL_RE = re.compile(
    r"^(?P<prefix>@?(?:etb|eti)|lbl|fn|jumptable|gap)_[0-9A-Fa-f]{8}$"
)


def projected_symbol_name(name: str, target_address: int) -> str:
    match = ADDRESS_SYMBOL_RE.match(name)
    if match is None:
        return name
    return f"{match.group('prefix')}_{target_address:08X}"


def source_data_identifiers(splits: list[SplitRange], root: Path = Path("src")) -> set[str]:
    """Keep legacy data names used by shared C, without treating comments as uses."""
    token = re.compile(
        r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|'
        r"'(?:\\.|[^'\\])*'|(?P<symbol>\blbl_[0-9A-Fa-f]{8}\b)"
    )
    names: set[str] = set()
    for unit in sorted({item.unit for item in splits}):
        path = root / unit
        if path.suffix not in {".c", ".cpp", ".cc", ".cxx"} or not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        names.update(match.group("symbol") for match in token.finditer(text) if match.group("symbol"))
    return names


def containing_range(
    ranges: list[PortedRange], address: int, *, target: bool
) -> PortedRange | None:
    starts = [item.target_start if target else item.source.start for item in ranges]
    index = bisect.bisect_right(starts, address) - 1
    if index < 0:
        return None
    item = ranges[index]
    end = item.target_end if target else item.source.end
    return item if address < end else None


def rewrite_symbol_line(
    line: str, *, name: str | None = None, address: int | None = None
) -> str:
    match = SYMBOL_LINE_RE.match(line)
    if match is None:
        raise ValueError(f"Unrecognized symbol line: {line}")
    result_name = name if name is not None else match.group(1)
    result_address = address if address is not None else int(match.group(3), 16)
    section_prefix = "." if " = ." in line else ""
    return (
        f"{result_name} = {section_prefix}{match.group(2)}:0x{result_address:08X};"
        f"{match.group(4)}"
    )


def render_projected_symbols(
    source_path: Path,
    target_path: Path,
    ported: list[PortedRange],
    matches: dict[int, FunctionSymbol],
) -> tuple[str, int, int, int]:
    """Project owned non-code symbols and canonical matched function names.

    Source symbols in coherently mapped non-code ranges carry the object sizes
    needed to keep split boundaries legal.  Target function boundaries remain
    authoritative; canonical EN names come from unique matches or coherent
    equal-count function runs.
    """

    return render_projected_symbol_texts(
        source_path.read_text(encoding="utf-8"), target_path.read_text(encoding="utf-8"), ported, matches
    )


def render_projected_symbol_texts(
    source_text: str,
    target_text: str,
    ported: list[PortedRange],
    matches: dict[int, FunctionSymbol],
    canonical_data_names: set[str] | None = None,
    data_references: dict | None = None,
) -> tuple[str, int, int, int]:
    canonical_data_names = canonical_data_names or set()
    source_lines = source_text.splitlines()
    target_lines = target_text.splitlines()
    claimed_by_section: dict[str, list[PortedRange]] = defaultdict(list)
    ranges_by_section: dict[str, list[PortedRange]] = defaultdict(list)
    for item in ported:
        if item.source.section not in CODE_SECTIONS:
            claimed_by_section[item.source.section].append(item)
            if (
                item.source.end - item.source.start
                == item.target_end - item.target_start
                and not (
                    data_references is not None
                    and item.source.section in {"sdata", "sbss"}
                    and any(target - address != item.target_start - item.source.start
                            for address, targets in data_references.items()
                            if item.source.start <= address < item.source.end
                            for target in targets)
                )
            ):
                ranges_by_section[item.source.section].append(item)
    for ranges in [*claimed_by_section.values(), *ranges_by_section.values()]:
        ranges.sort(key=lambda item: item.source.start)
    claimed_boundaries: dict[str, list[int]] = {}
    for section, ranges in claimed_by_section.items():
        claimed_boundaries[section] = sorted(
            {
                boundary
                for item in ranges
                for boundary in (item.target_start, item.target_end)
            }
        )

    section_order: dict[str, int] = {}
    records: list[tuple[str, int, int, str]] = []
    removed = 0
    for ordinal, line in enumerate(target_lines):
        match = SYMBOL_LINE_RE.match(line)
        if match is None:
            if line.strip():
                raise ValueError(f"Unrecognized target symbol line: {line}")
            continue
        section = match.group(2)
        address = int(match.group(3), 16)
        section_order.setdefault(section, len(section_order))
        ranges = ranges_by_section.get(section, [])
        if ranges and containing_range(ranges, address, target=True) is not None:
            removed += 1
            continue
        address_name_match = ADDRESS_SYMBOL_RE.match(match.group(1))
        if (
            address_name_match is not None
            and int(match.group(1).rsplit("_", 1)[1], 16) != address
            and match.group(1) not in canonical_data_names
        ):
            removed += 1
            continue
        if (
            section not in CODE_SECTIONS
            and address_name_match is not None
            and containing_range(
                claimed_by_section.get(section, []), address, target=True
            )
            is None
        ):
            size_match = re.search(r"\bsize:0x([0-9A-Fa-f]+)\b", line)
            if size_match is not None:
                end = address + int(size_match.group(1), 16)
                boundaries = claimed_boundaries.get(section, [])
                index = bisect.bisect_right(boundaries, address)
                if index < len(boundaries) and boundaries[index] < end:
                    removed += 1
                    continue
        records.append((section, address, ordinal, line))

    data_name_fallbacks: dict[int, str] = {}
    inserted = 0
    for ordinal, line in enumerate(source_lines):
        match = SYMBOL_LINE_RE.match(line)
        if match is None:
            if line.strip():
                raise ValueError(f"Unrecognized source symbol line: {line}")
            continue
        section = match.group(2)
        address = int(match.group(3), 16)
        ranges = ranges_by_section.get(section, [])
        item = containing_range(ranges, address, target=False) if ranges else None
        if item is None:
            continue
        target_address = item.target_start + (address - item.source.start)
        target_name = projected_symbol_name(match.group(1), target_address)
        if match.group(1) in canonical_data_names and target_name != match.group(1):
            data_name_fallbacks[len(records)] = target_name
            target_name = match.group(1)
        records.append(
            (
                section,
                target_address,
                ordinal,
                rewrite_symbol_line(line, name=target_name, address=target_address),
            )
        )
        inserted += 1

    # Source-used names can collide with a regional label outside the mapped
    # range, or with another name that had to retain its regional spelling.
    # Fall back without overwriting either owner; repeat to handle such chains.
    data_conflicts = 0
    while data_name_fallbacks:
        owners: dict[str, set[int]] = defaultdict(set)
        for _, address, _, line in records:
            record = SYMBOL_LINE_RE.match(line)
            assert record is not None
            owners[record.group(1)].add(address)
        conflicting = [index for index in data_name_fallbacks
                       if len(owners[SYMBOL_LINE_RE.match(records[index][3]).group(1)]) > 1]
        if not conflicting:
            break
        for index in conflicting:
            section, address, ordinal, line = records[index]
            records[index] = (section, address, ordinal,
                              rewrite_symbol_line(line, name=data_name_fallbacks.pop(index)))
            data_conflicts += 1

    desired_by_address: dict[int, str] = {}
    for split in ported:
        if split.source.section not in CODE_SECTIONS:
            continue
        function_pairs = paired_functions(split, matches)
        for source_function, target_function in function_pairs:
            desired_by_address[target_function.address] = source_function.name

    occupied: dict[str, set[int]] = defaultdict(set)
    for _, address, _, line in records:
        match = SYMBOL_LINE_RE.match(line)
        assert match is not None
        occupied[match.group(1)].add(address)

    rewritten_records: list[tuple[str, int, int, str]] = []
    renamed = 0
    conflicts = data_conflicts
    for section, address, ordinal, line in records:
        match = SYMBOL_LINE_RE.match(line)
        assert match is not None
        if section not in CODE_SECTIONS or "type:function" not in match.group(4):
            rewritten_records.append((section, address, ordinal, line))
            continue
        name = match.group(1)
        canonical = desired_by_address.get(address)
        if canonical is None:
            rewritten_records.append((section, address, ordinal, line))
            continue
        if any(owner != address for owner in occupied.get(canonical, set())):
            rewritten_records.append((section, address, ordinal, line))
            conflicts += 1
            continue
        if name != canonical:
            line = rewrite_symbol_line(line, name=canonical)
            renamed += 1
        rewritten_records.append((section, address, ordinal, line))

    rewritten_records.sort(
        key=lambda item: (
            section_order.get(item[0], len(section_order)),
            item[1],
            item[3],
        )
    )
    return (
        "\n".join(item[3] for item in rewritten_records) + "\n",
        renamed,
        conflicts,
        inserted - removed,
    )


@dataclass(frozen=True)
class VersionProjection:
    ported: list[PortedRange]
    matches: dict[int, FunctionSymbol]
    rejected: dict[str, int]
    preserved_alignment_gaps: int
    exact_symbol_range_remaps: int
    rejected_units: dict[str, tuple[str, ...]]
    anchor_counts: dict[str, tuple[int, int]]
    snapped_boundaries: int
    symbols: str
    renamed: int
    conflicts: int
    symbol_delta: int
    passes: int = 1


def recover_sdata_layout(
    source_dol: DolFile, target_dol: DolFile, source_splits: list[SplitRange],
    source_symbols: str, target_symbols: str, references: dict,
    canonical_data_names: set[str],
) -> tuple[dict[int, int], str]:
    """Recover initialized small data only with operand AND byte evidence.

    Individual names can survive a changed TU width. A whole range can move
    only when its start is directly referenced, every observed interior operand
    keeps its offset, and its complete initialization bytes agree with retail.
    Repeated scalar values alone cannot establish identity or ownership.
    """
    section = dol_section(target_dol, "sdata")
    start, end = section.address, section.address + section.size

    def project(address, size):
        targets = references.get(address, {})
        if len(targets) != 1:
            return None
        mapped = next(iter(targets))
        if not start <= mapped < mapped + size <= end:
            return None
        if any(target - source != mapped - address
               for source, destinations in references.items() if address <= source < address + size
               for target in destinations):
            return None
        if read_dol_range(source_dol, address, size) != read_dol_range(target_dol, mapped, size):
            return None
        return mapped

    proposals: dict[int, set[int]] = defaultdict(set)
    for split in source_splits:
        if split.section != "sdata" or split.start == split.end:
            continue
        mapped = project(split.start, split.end - split.start)
        if mapped is not None:
            proposals[split.start].add(mapped)
            proposals[split.end].add(mapped + split.end - split.start)
    boundaries = {edge: next(iter(values)) for edge, values in proposals.items() if len(values) == 1}

    replacements = []
    for line in source_symbols.splitlines():
        match = SYMBOL_LINE_RE.match(line)
        size_match = re.search(r"\bsize:0x([0-9A-Fa-f]+)", line)
        if match is None or match.group(2) != "sdata" or size_match is None:
            continue
        address, size = int(match.group(3), 16), int(size_match.group(1), 16)
        mapped = project(address, size)
        if mapped is None:
            continue
        name = (match.group(1) if match.group(1) in canonical_data_names
                else projected_symbol_name(match.group(1), mapped))
        replacements.append((mapped, mapped + size, name,
                             rewrite_symbol_line(line, name=name, address=mapped)))
    replacements.sort()
    if any(a[1] > b[0] for a, b in zip(replacements, replacements[1:])):
        raise ValueError("Retail initialized SDA projections overlap; no configuration written")
    return boundaries, replace_projected_section_symbols(target_symbols, "sdata", replacements)


def replace_projected_section_symbols(target_symbols, section, replacements):
    """Replace witnessed identities while retaining untouched target storage."""
    # A legacy EN identifier can coincide with an unrelated regional address
    # label. Keep that regional record unless this pass independently replaces
    # its storage too; give the imported identifier its normal regional fallback.
    existing = [match for line in target_symbols.splitlines()
                if (match := SYMBOL_LINE_RE.match(line)) and match.group(2) == section]
    adjusted = []
    for start, end, name, line in replacements:
        label = ADDRESS_SYMBOL_RE.match(name)
        if label is not None and int(name.rsplit("_", 1)[1], 16) != start:
            collisions = [int(m.group(3), 16) for m in existing if m.group(1) == name
                          and int(m.group(3), 16) == int(name.rsplit("_", 1)[1], 16)]
            if any(not any(a <= address < b for a, b, _, _ in replacements) for address in collisions):
                name = projected_symbol_name(name, start)
                line = rewrite_symbol_line(line, name=name)
        adjusted.append((start, end, name, line))
    replacements = adjusted
    names = {item[2] for item in replacements}
    new_lines = [(item[0], item[3]) for item in replacements]
    result = []
    insertion = None
    for line in target_symbols.splitlines():
        match = SYMBOL_LINE_RE.match(line)
        if match is None or match.group(2) != section:
            result.append(line)
            continue
        if insertion is None:
            insertion = len(result)
        address = int(match.group(3), 16)
        size_match = re.search(r"\bsize:0x([0-9A-Fa-f]+)", line)
        size = int(size_match.group(1), 16) if size_match else 1
        if match.group(1) in names or any(
            start < address + size and address < end for start, end, _, _ in replacements
        ):
            continue
        new_lines.append((address, line))
    insertion = len(result) if insertion is None else insertion
    result[insertion:insertion] = [line for _, line in sorted(new_lines)]
    return "\n".join(result) + "\n"


def recover_sbss_layout(
    source_dol: DolFile, target_dol: DolFile, source_splits: list[SplitRange],
    source_symbols: str, target_symbols: str, references: dict,
    canonical_data_names: set[str],
) -> tuple[dict[int, int], str]:
    """Project small BSS from operand anchors, preserving local layout changes.

    Infer edges between operands with the same address delta. At a layout
    transition, bound ownership by the surviving, individually mapped symbols.
    Changed-layout TUs need individually anchored symbols; their whole section
    must not overwrite those identities with a constant offset on later passes.
    """
    def bounds(dol):
        section = dol_section(dol, "sdata")
        return section.address + section.size, dol_section(dol, "sdata2").address

    source_start, source_end = bounds(source_dol)
    target_start, target_end = bounds(target_dol)
    if any(len(targets) != 1 or not target_start <= next(iter(targets)) < target_end
           for address, targets in references.items() if source_start <= address < source_end):
        raise ValueError("Conflicting or migrated retail SDA storage requires an explicit layout audit")
    anchors = {
        address: next(iter(targets)) for address, targets in references.items()
        if source_start <= address < source_end and len(targets) == 1
        and target_start <= next(iter(targets)) < target_end
    }
    anchors[source_start] = target_start
    anchors[source_end] = target_end
    addresses = sorted(anchors)
    if any(anchors[a] >= anchors[b] for a, b in zip(addresses, addresses[1:])):
        raise ValueError("Retail SDA storage changes order; no configuration written")

    def project(address):
        if address in anchors:
            return anchors[address]
        index = bisect.bisect_left(addresses, address)
        if 0 < index < len(addresses):
            before, after = addresses[index - 1:index + 1]
            if anchors[before] - before == anchors[after] - after:
                return address + anchors[before] - before
        return None

    proposals: dict[int, set[int]] = defaultdict(set)
    source_spans = parse_symbol_spans(source_symbols).get("sbss", ())
    for split in source_splits:
        if split.section != "sbss":
            continue
        owned = [span for span in source_spans if split.start <= span.start < split.end]
        mapped_spans = [(span, project(span.start)) for span in owned]
        mapped_spans = [(span, address) for span, address in mapped_spans if address is not None]
        for edge in (split.start, split.end):
            mapped = project(edge)
            if mapped is None and mapped_spans:
                # Do not resurrect an unanchored leading/trailing global in a
                # changed-layout TU (e.g. the removed walk-group checksum).
                # Claim only the bounded storage of the surviving symbols.
                mapped = (min(address for _, address in mapped_spans) if edge == split.start
                          else max(address + span.size for span, address in mapped_spans))
            if mapped is not None and target_start <= mapped <= target_end:
                proposals[edge].add(mapped)
    boundaries = {edge: next(iter(values)) for edge, values in proposals.items()
                  if len(values) == 1}

    # Rebuild only evidenced symbol spans. Stale projected names must not veto
    # the instruction evidence or collide with the same identity at its real
    # address. Target-only storage outside these spans remains untouched.
    replacements: list[tuple[int, int, str, str]] = []
    for line in source_symbols.splitlines():
        match = SYMBOL_LINE_RE.match(line)
        size_match = re.search(r"\bsize:0x([0-9A-Fa-f]+)", line)
        if match is None or match.group(2) != "sbss" or size_match is None:
            continue
        address = int(match.group(3), 16)
        size = int(size_match.group(1), 16)
        mapped = project(address)
        if mapped is None or not target_start <= mapped < mapped + size <= target_end:
            continue
        if any(target - source != mapped - address
               for source, targets in references.items() if address <= source < address + size
               for target in targets):
            continue
        next_anchor = bisect.bisect_left(addresses, address + size)
        if next_anchor < len(addresses) and mapped + size > anchors[addresses[next_anchor]]:
            continue
        name = (match.group(1) if match.group(1) in canonical_data_names
                else projected_symbol_name(match.group(1), mapped))
        replacements.append((mapped, mapped + size, name,
                             rewrite_symbol_line(line, name=name, address=mapped)))
    replacements.sort()
    if any(before[1] > after[0] for before, after in zip(replacements, replacements[1:])):
        raise ValueError("Retail SDA symbol projections overlap; no configuration written")
    return boundaries, replace_projected_section_symbols(target_symbols, "sbss", replacements)


def project_symbol_snapshot(
    source_dol: DolFile, source_splits: list[SplitRange], source_symbols: str,
    target_dol: DolFile, target_symbols: str,
    canonical_data_names: set[str] | None = None,
) -> VersionProjection:
    source_functions = parse_function_symbols(source_symbols)
    target_functions = parse_function_symbols(target_symbols)
    matches = unique_function_matches(
        source_dol, source_functions, target_dol, target_functions
    )
    sbss_boundaries = sdata_boundaries = None
    references = None
    if any(split.section in {"sbss", "sdata"} for split in source_splits):
        references = sda_reference_pairs(source_dol, source_functions, target_dol, target_functions)
    if any(split.section == "sdata" for split in source_splits):
        sdata_boundaries, target_symbols = recover_sdata_layout(
            source_dol, target_dol, source_splits, source_symbols, target_symbols,
            references, canonical_data_names or set(),
        )
    if any(split.section == "sbss" for split in source_splits):
        sbss_boundaries, target_symbols = recover_sbss_layout(
            source_dol, target_dol, source_splits, source_symbols, target_symbols,
            references, canonical_data_names or set(),
        )
    source_symbol_spans = parse_symbol_spans(source_symbols)
    target_symbol_spans = parse_symbol_spans(target_symbols)
    target_named_symbol_span_index = symbol_span_index(target_symbol_spans)
    target_all_symbol_span_index = symbol_span_index(
        target_symbol_spans, include_address_symbols=True
    )
    boundary_maps, anchor_counts = build_all_boundary_maps(
        source_splits,
        source_dol,
        target_dol,
        source_functions,
        matches,
        target_all_symbol_span_index,
    )
    if sbss_boundaries is not None:
        boundary_maps["sbss"] = sbss_boundaries
        anchor_counts["sbss"] = (
            sum(edge in references for edge in sbss_boundaries), len(sbss_boundaries)
        )
    if sdata_boundaries is not None:
        boundary_maps["sdata"].update(sdata_boundaries)
        direct_count, _ = anchor_counts["sdata"]
        source_edges = {edge for split in source_splits if split.section == "sdata"
                        for edge in (split.start, split.end)}
        anchor_counts["sdata"] = (
            direct_count, sum(edge in boundary_maps["sdata"] for edge in source_edges)
        )
    boundary_maps, snapped_boundaries = snap_symbol_boundaries(
        source_splits,
        boundary_maps,
        source_dol,
        target_dol,
        source_symbol_spans,
        target_symbol_spans,
        target_named_symbol_span_index,
        target_all_symbol_span_index,
    )
    (
        ported,
        rejected,
        preserved_alignment_gaps,
        exact_symbol_range_remaps,
        rejected_units,
    ) = port_coherent_units(
        source_splits,
        source_functions,
        target_functions,
        boundary_maps,
        target_named_symbol_span_index,
        target_all_symbol_span_index,
        source_dol,
        target_dol,
        source_symbol_spans,
        target_symbol_spans,
    )
    symbols, renamed, conflicts, symbol_delta = render_projected_symbol_texts(
        source_symbols, target_symbols, ported, matches, canonical_data_names, references
    )
    return VersionProjection(
        ported=ported, matches=matches, rejected=rejected,
        preserved_alignment_gaps=preserved_alignment_gaps,
        exact_symbol_range_remaps=exact_symbol_range_remaps,
        rejected_units=rejected_units, anchor_counts=anchor_counts,
        snapped_boundaries=snapped_boundaries, symbols=symbols,
        renamed=renamed, conflicts=conflicts, symbol_delta=symbol_delta,
    )


def project_version(
    source_dol: DolFile, source_splits: list[SplitRange], source_symbols: str,
    target_dol: DolFile, target_symbols: str, *, max_passes: int = 8,
    canonical_data_names: set[str] | None = None,
) -> VersionProjection:
    """Refine symbol boundaries before publishing one internally consistent result.

    Coherent ranges reveal finer target symbol extents. Those extents can unlock
    the existing binary-chain and ownership checks on the next pass. All passes
    remain in memory; unstable projections must not partially update configs.
    """
    seen = {target_symbols}
    renamed = symbol_delta = 0
    for iteration in range(1, max_passes + 1):
        result = project_symbol_snapshot(
            source_dol, source_splits, source_symbols, target_dol, target_symbols, canonical_data_names
        )
        renamed += result.renamed
        symbol_delta += result.symbol_delta
        if result.symbols == target_symbols:
            return replace(result, renamed=renamed, symbol_delta=symbol_delta, passes=iteration)
        if result.symbols in seen:
            raise ValueError("Regional symbol projection cycles; no configuration written")
        seen.add(result.symbols)
        target_symbols = result.symbols
    raise ValueError(
        f"Regional symbol projection did not stabilize in {max_passes} passes; no configuration written"
    )


def write_lf_text(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)


def report_unit_is_exact(unit: dict) -> bool:
    """Require complete byte coverage even when objdiff omits zero fields."""
    measures = unit.get("measures", {})
    scored = [
        measures[key]
        for key in ("fuzzy_match_percent", "matched_data_percent")
        if key in measures
    ]
    return bool(scored) and all(value == 100.0 for value in scored) and all(
        int(measures.get(f"matched_{kind}", 0))
        == int(measures.get(f"total_{kind}", 0))
        for kind in ("code", "data")
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", help="target version under config/ and orig/")
    parser.add_argument(
        "--source", default="GSAE01", help="source version (default: GSAE01)"
    )
    parser.add_argument(
        "--write", action="store_true", help="write target splits and mappings"
    )
    parser.add_argument(
        "--write-matching",
        action="store_true",
        help="write exact source units from the target's current report",
    )
    parser.add_argument(
        "--verbose", action="store_true", help="list rejected translation units"
    )
    args = parser.parse_args()

    source_root = Path("config") / args.source
    target_root = Path("config") / args.target
    try:
        source_dol = verified_dol(Path("orig") / args.source / "sys" / "main.dol", source_root / "config.yml")
        target_dol = verified_dol(Path("orig") / args.target / "sys" / "main.dol", target_root / "config.yml")
    except (ValueError, FileNotFoundError) as error:
        parser.error(str(error))
    target_header, _ = load_splits(target_root / "splits.txt")
    _, source_splits = load_splits(source_root / "splits.txt")
    try:
        projection = project_version(
            source_dol, source_splits, (source_root / "symbols.txt").read_text(encoding="utf-8"),
            target_dol, (target_root / "symbols.txt").read_text(encoding="utf-8"),
            canonical_data_names=source_data_identifiers(source_splits),
        )
    except ValueError as error:
        parser.error(str(error))
    ported, matches = projection.ported, projection.matches
    rejected, rejected_units = projection.rejected, projection.rejected_units
    anchor_counts = projection.anchor_counts
    snapped_boundaries = projection.snapped_boundaries
    exact_symbol_range_remaps = projection.exact_symbol_range_remaps
    preserved_alignment_gaps = projection.preserved_alignment_gaps
    mappings = build_symbol_mappings(ported, matches)
    split_text = render_splits(target_header, ported)
    mapping_text = json.dumps(mappings, indent=2, sort_keys=True) + "\n"

    accepted_units = len({item.source.unit for item in ported})
    source_units = len({item.unit for item in source_splits})
    code_bytes = sum(
        item.target_end - item.target_start
        for item in ported
        if item.source.section in CODE_SECTIONS
    )
    data_bytes = sum(
        item.target_end - item.target_start
        for item in ported
        if item.source.section not in CODE_SECTIONS
    )
    mapped_symbols = sum(len(unit) for unit in mappings.values())
    print(
        f"{args.source} -> {args.target}: "
        f"{len(matches)} function anchors, "
        f"{accepted_units}/{source_units} coherent units, "
        f"{len(ported)}/{len(source_splits)} ranges, "
        f"0x{code_bytes:X} target code bytes, "
        f"0x{data_bytes:X} target data bytes, "
        f"{mapped_symbols} symbol mappings, "
        f"{snapped_boundaries} proven symbol-edge snaps, "
        f"{exact_symbol_range_remaps} exact symbol-range remaps, "
        f"{preserved_alignment_gaps} preserved alignment gaps"
    )
    print(f"  Symbol refinement stabilized in {projection.passes} passes")
    for section, counts in anchor_counts.items():
        boundaries = {
            address
            for split in source_splits
            if split.section == section
            for address in (split.start, split.end)
        }
        print(
            f"  {section}: {counts[0]} direct, {counts[1]}/{len(boundaries)} mapped boundaries"
        )
    for reason, count in rejected.items():
        print(f"  skipped {count}: {reason}")
        if args.verbose:
            for unit in rejected_units.get(reason, ()):
                print(f"    {unit}")

    if args.write:
        write_lf_text(target_root / "splits.txt", split_text)
        write_lf_text(target_root / "symbol_mappings.json", mapping_text)
        canonical_symbols = projection.symbols
        renamed, conflicts, symbol_delta = projection.renamed, projection.conflicts, projection.symbol_delta
        write_lf_text(target_root / "symbols.txt", canonical_symbols)
        print(f"Wrote {target_root / 'splits.txt'}")
        print(f"Wrote {target_root / 'symbol_mappings.json'}")
        print(f"Renamed {renamed} functions in {target_root / 'symbols.txt'}")
        print(f"Projected non-code symbols (net {symbol_delta:+d} entries)")
        if conflicts:
            print(f"Preserved {conflicts} regional symbol names with canonical-name conflicts")
    if args.write_matching:
        report_path = Path("build") / args.target / "report.json"
        report = json.loads(report_path.read_text(encoding="utf-8"))
        exact_sources: set[str] = set()
        for unit in report.get("units", []):
            source_path = unit.get("metadata", {}).get("source_path")
            if not source_path:
                continue
            if report_unit_is_exact(unit):
                exact_sources.add(source_path.removeprefix("src/").replace("\\", "/"))
        manifest_path = target_root / "matching_units.txt"
        write_lf_text(
            manifest_path,
            "# Generated by tools/version_progress.py --write-matching\n"
            + "\n".join(sorted(exact_sources))
            + "\n",
        )
        print(f"Wrote {len(exact_sources)} exact units to {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
