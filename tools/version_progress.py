#!/usr/bin/env python3
"""Project coherent translation units between retail DOL versions.

The active EN v1.0 configuration remains the source of translation-unit names.
Code, initialized data, exception metadata, and BSS boundaries are inferred from
unique normalized binary anchors and stable address-delta corridors. A source
unit is claimed only when every owned section maps legally in the target;
uncertain ranges stay autogenerated and remain in the progress denominator.
"""

from __future__ import annotations

