#!/usr/bin/env python3
"""Verify selected source objects against a complete retail DOL link.

Use already configured/built objects. First link every extracted retail object,
then substitute only the requested source units. Both outputs must exactly equal
the hash-verified original DOL. This checks linker garbage collection, final
addresses and relocations that a normalized object report can hide.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

from version_progress import verified_dol


ROOT = Path(__file__).resolve().parents[1]


def verify(version: str, units: set[str], output: Path) -> str:
    build = Path("build") / version
    original = verified_dol(ROOT / "orig" / version / "sys/main.dol",
                            ROOT / "config" / version / "config.yml")
    config = json.loads((ROOT / build / "config.json").read_text())
    known = {unit["name"] for unit in config["units"] if not unit.get("autogenerated")}
    if missing := units - known:
        raise ValueError("Source units absent from build config: " + ", ".join(sorted(missing)))
    output.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha1(original.data).hexdigest()
    for label, selected in (("retail", set()), ("source", units)):
        objects = []
        for unit in config["units"]:
            path = Path(unit["object"])
            if unit["name"] in selected:
                path = build / "src" / path.relative_to(build / "obj")
            if not (ROOT / path).is_file():
                raise ValueError(f"Missing object: {path}; configure and build this version first")
            objects.append('"' + path.as_posix() + '"')
        response = output / f"{label}.rsp"
        response.write_bytes(("\r\n".join(objects) + "\r\n").encode())
        elf, dol = output / f"{label}.elf", output / f"{label}.dol"
        command = ["build/tools/wibo", "build/compilers/GC/1.3.2/mwldeppc.exe",
                   "-fp", "hardware", "-nodefaults", "-lcf", config["ldscript"],
                   "-o", str(elf), "@" + str(response)]
        with (output / f"{label}.log").open("w") as log:
            subprocess.run(command, cwd=ROOT, check=True, timeout=30,
                           stdout=log, stderr=subprocess.STDOUT)
            subprocess.run(["build/tools/dtk", "elf2dol", str(elf), str(dol)],
                           cwd=ROOT, check=True, timeout=30, stdout=log, stderr=subprocess.STDOUT)
        result = dol.read_bytes()
        if result != original.data:
            raise ValueError(f"{label} link differs from retail: "
                             f"{hashlib.sha1(result).hexdigest()} != {digest}; inspect {output}")
        print(f"{version} {label}: retail SHA-1 {digest}", flush=True)
    return digest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version")
    parser.add_argument("units", nargs="+", help="source paths relative to src/")
    parser.add_argument("--output", type=Path, help="directory for ELF/DOL files and linker logs")
    args = parser.parse_args()
    output = args.output or Path(tempfile.mkdtemp(prefix="sfa-source-link-"))
    units = {unit.removeprefix("src/") for unit in args.units}
    verify(args.version, units, output.resolve())
    print(f"Verified {len(units)} source substitutions; artifacts: {output.resolve()}")


if __name__ == "__main__":
    main()
